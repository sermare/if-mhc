    df = load_corpus(rebuild=True)
    print(f"{len(df):,} designs")
    print(df.groupby(["dataset", "model", "arm"], observed=True)
            .agg(complexes=("complex", "nunique"), n=("seq", "size"),
                 unique=("seq", "nunique"), recovery=("recovery", "mean")).to_string())
